/// A fixture-backed stand-in for [PayslipRemoteDataSource].
///
/// NOT A BACKEND — see [MockSupport]. The figures are invented and are not
/// anyone's pay.
///
/// [downloadPayslipPdf] returns a genuine, minimal PDF rather than random
/// bytes. That matters: the download writes a file and hands it to the
/// platform viewer, and a fake byte string would fail to open — making the
/// flow look broken when it is not. The generated document says plainly on
/// its face that it is sample data.
class PayslipMockDataSource implements PayslipRemoteDataSource {
  const PayslipMockDataSource();

  @override
  Future<PaginatedResponse<PayslipSummaryModel>> getPayslips({
    required PageRequest page,
    int? year,
  }) async {
    await MockSupport.delay();

    List<PayslipSummaryModel> all = MockFixtures.instance.payslips;
    if (year != null) {
      all = all.where((PayslipSummaryModel p) => p.year == year).toList();
    }

    final List<PayslipSummaryModel> items = MockSupport.page(
      all,
      page.pageNumber,
      page.pageSize,
    );
    final int totalPages = all.isEmpty
        ? 1
        : (all.length / page.pageSize).ceil();

    return PaginatedResponse<PayslipSummaryModel>(
      items: items,
      pageNumber: page.pageNumber,
      pageSize: page.pageSize,
      totalCount: all.length,
      totalPages: totalPages,
      hasNextPage: page.pageNumber < totalPages,
      hasPreviousPage: page.pageNumber > 1,
    );
  }

  @override
  Future<PayslipDetailModel> getPayslipDetail(String id) async {
    await MockSupport.delay(const Duration(milliseconds: 400));

    final PayslipDetailModel? detail = MockFixtures.instance.payslipDetail(id);
    if (detail == null) {
      throw const NotFoundException('That payslip was not found.');
    }
    return detail;
  }

  @override
  Future<Uint8List> downloadPayslipPdf(
    String id, {
    void Function(double progress)? onProgress,
  }) async {
    // Walk the progress bar so the determinate UI path is exercised.
    for (int step = 1; step <= 4; step++) {
      await MockSupport.delay(const Duration(milliseconds: 200));
      onProgress?.call(step / 4);
    }

    final PayslipDetailModel? detail = MockFixtures.instance.payslipDetail(id);
    if (detail == null) {
      throw const NotFoundException('That payslip was not found.');
    }

    return _SamplePdf.build(
      title: 'SAMPLE PAYSLIP - NOT REAL DATA',
      lines: <String>[
        'Period: ${detail.periodLabel ?? '${detail.year}-${detail.month}'}',
        'Employee: ${MockSupport.fullName} (${MockSupport.employeeId})',
        '',
        'This document was generated by the app in mock mode.',
        'It is not a payroll record and contains invented figures.',
      ],
    );
  }
}

/// Builds a minimal, valid single-page PDF.
///
/// Hand-assembled rather than pulled in from a PDF package: the only purpose
/// is to prove the download-and-open path works end to end, and a whole
/// rendering dependency for a throwaway fixture is not worth the weight.
///
/// The structure is the smallest conforming document — catalog, pages, page,
/// font, content stream — with a correct cross-reference table, because an
/// incorrect one makes viewers reject the file.
abstract final class _SamplePdf {
  static Uint8List build({required String title, required List<String> lines}) {
    final StringBuffer text = StringBuffer()
      ..writeln('BT')
      ..writeln('/F1 16 Tf')
      ..writeln('60 760 Td')
      ..writeln('(${_escape(title)}) Tj')
      ..writeln('/F1 11 Tf');

    for (final String line in lines) {
      text
        ..writeln('0 -22 Td')
        ..writeln('(${_escape(line)}) Tj');
    }
    text.writeln('ET');

    final String content = text.toString();

    final List<String> objects = <String>[
      '<< /Type /Catalog /Pages 2 0 R >>',
      '<< /Type /Pages /Kids [3 0 R] /Count 1 >>',
      '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] '
          '/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>',
      '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
      '<< /Length ${content.length} >>\nstream\n$content\nendstream',
    ];

    final StringBuffer pdf = StringBuffer('%PDF-1.4\n');
    final List<int> offsets = <int>[];

    for (int i = 0; i < objects.length; i++) {
      offsets.add(pdf.length);
      pdf.write('${i + 1} 0 obj\n${objects[i]}\nendobj\n');
    }

    final int xrefOffset = pdf.length;
    pdf
      ..write('xref\n0 ${objects.length + 1}\n')
      ..write('0000000000 65535 f \n');
    for (final int offset in offsets) {
      pdf.write('${offset.toString().padLeft(10, '0')} 00000 n \n');
    }
    pdf
      ..write('trailer\n<< /Size ${objects.length + 1} /Root 1 0 R >>\n')
      ..write('startxref\n$xrefOffset\n%%EOF');

    return Uint8List.fromList(pdf.toString().codeUnits);
  }

  /// Escapes the characters that would otherwise terminate a PDF string.
  static String _escape(String value) => value
      .replaceAll(r'\', r'\\')
      .replaceAll('(', r'\(')
      .replaceAll(')', r'\)');
}
